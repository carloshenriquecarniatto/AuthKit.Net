#!/usr/bin/env node
/**
 * Writes the release version into every artifact manifest.
 * Called by semantic-release (prepareCmd) with the computed version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const version = process.argv[2];

if (!version || !/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`set-version: invalid version "${version ?? ''}".`);
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const propsPath = join(root, 'src', 'dotnet', 'version.props');
writeFileSync(
  propsPath,
  `<Project>
  <!--
    Generated by scripts/set-version.mjs during a release. Do not edit by hand.
  -->
  <PropertyGroup>
    <Version>${version}</Version>
  </PropertyGroup>
</Project>
`,
);

const contractsPackagePath = join(root, 'contracts', 'package.json');
const contractsPackage = JSON.parse(readFileSync(contractsPackagePath, 'utf8'));
contractsPackage.version = version;
writeFileSync(contractsPackagePath, `${JSON.stringify(contractsPackage, null, 2)}\n`);

const rootPackagePath = join(root, 'package.json');
const rootPackage = JSON.parse(readFileSync(rootPackagePath, 'utf8'));
rootPackage.version = version;
writeFileSync(rootPackagePath, `${JSON.stringify(rootPackage, null, 2)}\n`);

console.log(`set-version: wrote ${version} to .NET, @authkit/contracts and root manifests.`);
